// internal/routes/routes.go
// Package routes provides the routing for the application.
// It registers the routes for the different resources.
// It also registers the Swagger documentation.
// It uses the handlers package to handle the requests.
// It uses the mux package to handle the routing.
// It uses the httpSwagger package to serve the Swagger documentation.
// It uses the swaggo package to generate the Swagger documentation.
// It uses the gorilla/mux package to handle the routing.
package routes

import (
	"log"
	"myanimeapi/pkg/handlers"
	"myanimeapi/pkg/middleware"
	"net/http"

	_ "myanimeapi/cmd/docs" // This is required to load the docs generated by Swaggo

	"github.com/gorilla/mux"
	httpSwagger "github.com/swaggo/http-swagger"
)

// RegisterRoutes registers all routes for the application
func RegisterRoutes(router *mux.Router, swaggerURL string, animeHandler *handlers.AnimeHandler, userHandler *handlers.UserHandler, reviewHandler *handlers.ReviewHandler, authHandler *handlers.AuthHandler) {
	// Apply global middleware
	router.Use(middleware.LoggingMiddleware)
	log.Println("Global middleware registered")

	// Health check endpoint
	router.HandleFunc("/health", func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusOK)
		w.Write([]byte("OK"))
	}).Methods("GET")
	log.Println("Health check endpoint registered")

	// Register anime routes
	animeHandler.RegisterAnimeRoutes(router)
	log.Println("Anime routes registered")

	// Register user routes
	userHandler.RegisterUserRoutes(router)
	log.Println("User routes registered")

	// Register review routes
	reviewHandler.RegisterReviewRoutes(router)
	log.Println("Review routes registered")

	// Register auth routes
	authHandler.RegisterAuthRoutes(router)
	log.Println("Auth routes registered")

	// Register Swagger documentation
	router.PathPrefix("/swagger/").Handler(httpSwagger.Handler(
		httpSwagger.URL(swaggerURL), // Path to swagger.json
	))
	log.Println("Swagger documentation registered")
}
